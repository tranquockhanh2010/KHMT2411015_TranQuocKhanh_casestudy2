const router = require('express').Router();
const c = require('../controllers/taskController');
const { authenticate } = require('../middleware/authMiddleware');
const { requireRole } = require('../middleware/permissionMiddleware');
router.use(authenticate);
router.get('/', c.list);
router.post('/', c.create);
router.get('/:id', requireRole('owner', 'editor', 'viewer'), c.get);
router.patch('/:id', requireRole('owner', 'editor'), c.update);
router.patch('/:id/status', requireRole('owner', 'editor'), c.update);
router.delete('/:id', requireRole('owner'), c.remove);
router.get('/:id/shares', requireRole('owner', 'editor', 'viewer'), c.shares);
router.post('/:id/shares', requireRole('owner'), c.share);
router.delete('/:id/shares/:userId', requireRole('owner'), c.unshare);
router.get('/:id/assignees', requireRole('owner', 'editor', 'viewer'), c.shares);
router.post('/:id/assignees', requireRole('owner'), c.share);
router.patch('/:id/assignees/:userId', requireRole('owner'), c.updateShare);
router.delete('/:id/assignees/:userId', requireRole('owner'), c.unshare);
router.get('/:id/activity', requireRole('owner', 'editor', 'viewer'), c.activity);
module.exports = router;
